using System.Diagnostics.CodeAnalysis;
using Microsoft.Extensions.AI;
using Microsoft.Extensions.VectorData;
using Microsoft.Extensions.VectorData.ProviderServices;

namespace CommunityToolkit.VectorData.Milvus;

internal sealed class MilvusModelBuilder() : CollectionModelBuilder(new()
{
    RequiresAtLeastOneVector = true,
    SupportsMultipleVectors = true,
})
{
    // Reserved tokens from Milvus 2.6's Plan.g4 grammar cannot be unquoted field names.
    private static readonly HashSet<string> s_reservedNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "like", "exists", "text_match", "phrase_match", "random_sample", "interval", "iso",
        "and", "or", "not", "in", "true", "false", "null", "is",
        "json_contains", "json_contains_all", "json_contains_any",
        "array_contains", "array_contains_all", "array_contains_any", "array_length",
        "st_equals", "st_touches", "st_overlaps", "st_crosses", "st_contains", "st_intersects", "st_within", "st_dwithin",
    };

    internal const string SupportedVectorTypes = "ReadOnlyMemory<float>, Embedding<float>, float[]";

    private const int MaxFieldNameLength = 255;

    protected override void ValidateKeyProperty(KeyPropertyModel keyProperty)
    {
        base.ValidateKeyProperty(keyProperty);
        if (keyProperty.Type != typeof(long) && keyProperty.Type != typeof(string) && keyProperty.Type != typeof(Guid))
        {
            throw new NotSupportedException("Milvus keys must be long, string or Guid.");
        }
        if (keyProperty.IsAutoGenerated && keyProperty.Type != typeof(Guid))
        {
            throw new NotSupportedException("Auto-generation is supported only for Guid keys.");
        }
    }

    protected override void ValidateProperty(PropertyModel propertyModel, VectorStoreCollectionDefinition? definition)
    {
        base.ValidateProperty(propertyModel, definition);
        var name = propertyModel.StorageName;
        if (name.Length == 0 || name.Length > MaxFieldNameLength || !(IsLetter(name[0]) || name[0] == '_')
            || name.Any(c => !(IsLetter(c) || c is >= '0' and <= '9' || c == '_')))
        {
            throw new NotSupportedException($"Invalid Milvus field name '{name}'. Use ASCII letters, digits and underscores, starting with a letter or underscore.");
        }
        if (s_reservedNames.Contains(name))
        {
            throw new NotSupportedException($"Milvus field name '{name}' is a reserved keyword. Configure a different StorageName.");
        }
        if (propertyModel is VectorPropertyModel vector)
        {
            _ = MilvusCollectionCreateMapping.GetMetric(vector);
            _ = MilvusCollectionCreateMapping.GetIndexType(vector);
        }
        if (propertyModel is DataPropertyModel { IsFullTextIndexed: true } dataProperty)
        {
            if (dataProperty.Type != typeof(string))
            {
                throw new InvalidOperationException($"Property {nameof(VectorStoreDataProperty.IsFullTextIndexed)} on {nameof(VectorStoreDataProperty)} '{dataProperty.ModelName}' is set to true, but the property type is not a string. The Milvus VectorStore supports {nameof(VectorStoreDataProperty.IsFullTextIndexed)} on string properties only.");
            }
            var bm25FieldName = MilvusCollectionCreateMapping.GetBm25FieldName(dataProperty);
            if (bm25FieldName.Length > MaxFieldNameLength)
            {
                throw new NotSupportedException($"Milvus field name '{name}' is too long for full-text indexing: its BM25 field '{bm25FieldName}' would exceed {MaxFieldNameLength} characters. Configure a shorter StorageName.");
            }
        }

        static bool IsLetter(char c) => c is >= 'a' and <= 'z' or >= 'A' and <= 'Z';
    }

    protected override void Validate(Type? type, VectorStoreCollectionDefinition? definition)
    {
        base.Validate(type, definition);

        // Each full-text indexed property adds a hidden BM25 field, which no property can be stored under.
        foreach (var fullTextProperty in DataProperties.Where(p => p.IsFullTextIndexed))
        {
            var bm25FieldName = MilvusCollectionCreateMapping.GetBm25FieldName(fullTextProperty);
            if (Properties.FirstOrDefault(p => p.StorageName == bm25FieldName) is { } conflict)
            {
                throw new InvalidOperationException($"Property '{conflict.ModelName}' is mapped to storage name '{bm25FieldName}', which the Milvus VectorStore uses for the BM25 field of the full-text indexed property '{fullTextProperty.ModelName}'. Configure a different StorageName.");
            }
        }
    }

    protected override bool IsDataPropertyTypeValid(Type type, [NotNullWhen(false)] out string? supportedTypes)
    {
        supportedTypes = "string, int, long, float, double, bool, nullable versions of these value types, and arrays/lists of non-nullable scalars";
        if (MilvusFieldMapping.GetElementType(type) is { } elementType)
        {
            type = elementType;
        }
        else
        {
            type = Nullable.GetUnderlyingType(type) ?? type;
        }
        return type == typeof(string) || type == typeof(int) || type == typeof(long)
            || type == typeof(float) || type == typeof(double) || type == typeof(bool);
    }

    protected override bool IsVectorPropertyTypeValid(Type type, [NotNullWhen(false)] out string? supportedTypes)
        => IsVectorPropertyTypeValidCore(type, out supportedTypes);

    internal static bool IsVectorPropertyTypeValidCore(Type type, [NotNullWhen(false)] out string? supportedTypes)
    {
        supportedTypes = SupportedVectorTypes;
        return type == typeof(ReadOnlyMemory<float>) || type == typeof(ReadOnlyMemory<float>?)
            || type == typeof(Embedding<float>) || type == typeof(float[]);
    }
}
